// Run with Storybook on 6006 (or WHIP_STORYBOOK_URL). No product daemon required.
import { chromium, expect } from '@playwright/test';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 900, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const url = process.env.WHIP_STORYBOOK_URL ?? 'http://127.0.0.1:6006';
try {
  await page.goto(`${url}/iframe.html?id=whip-textarea-suggestions--multiline&viewMode=story&whip_a11y=manual`);
  const input = page.getByRole('textbox', { name: 'Message' });
  await input.fill('/');
  await expect(page.getByRole('listbox', { name: 'Skills' })).toBeVisible();
  await expect(input).toBeFocused();
  await expect(input).toHaveAttribute('aria-activedescendant', /.+-0$/);
  await input.press('ArrowDown');
  await expect(input).toHaveAttribute('aria-activedescendant', /.+-1$/);
  await input.fill('/p');
  await expect(input).toHaveAttribute('aria-activedescendant', /.+-0$/);
  await input.fill('/');
  await expect(input).toHaveAttribute('aria-activedescendant', /.+-0$/);
  await input.press('ArrowDown');
  await input.press('Enter');
  await expect(input).toHaveValue('$frontend-design ');
  await expect(input).toBeFocused();
  await expect(page.getByLabel('Send count')).toHaveText('0');
  await input.fill('/');
  await page.getByRole('option', { name: /ponytail/ }).click();
  await expect(input).toHaveValue('$ponytail ');
  await expect(input).toBeFocused();
  await input.fill('/');
  await input.press('Escape');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await expect(input).toHaveValue('/');
  await input.fill('/new');
  await input.press('Shift+Enter');
  await expect(input).toHaveValue('/new\n');
  await input.dispatchEvent('compositionstart');
  await input.press('Enter');
  await input.dispatchEvent('compositionend');
  await expect(page.getByLabel('Send count')).toHaveText('0');
  await input.fill('/');
  await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') });
  // Base UI focus guards are intentionally aria-hidden/tabbable sentinels, not authored controls.
  const violations = await page.evaluate(async () => (await axe.run({ include: [['body']], exclude: [['[data-base-ui-focus-guard]']] }, { rules: { 'region': { enabled: false } } })).violations);
  if (violations.length) throw new Error(JSON.stringify(violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.html) })), null, 2));
  await page.setViewportSize({ width: 375, height: 700 });
  await expect(page.getByRole('listbox')).toBeVisible();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Narrow viewport overflow');
  await input.press('Tab');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await page.goto(`${url}/iframe.html?id=whip-textarea-suggestions--empty&viewMode=story&whip_a11y=manual`);
  await input.fill('/'); await input.press('Enter');
  await expect(input).toHaveValue('/');
  await expect(page.getByLabel('Send count')).toHaveText('0');
  await page.goto(`${url}/iframe.html?id=whip-textarea-suggestions--long-list&viewMode=story&whip_a11y=manual`);
  await input.fill('/');
  await expect(page.getByRole('listbox')).toBeVisible();
  const scroll = await page.evaluate(() => scrollY);
  for (let row = 0; row < 31; row++) await input.press('ArrowDown');
  await expect(input).toHaveAttribute('aria-activedescendant', /.+-31$/);
  if (await page.getByRole('listbox').evaluate(el => el.scrollTop) === 0) throw new Error('List did not scroll');
  if (await page.evaluate(() => scrollY) !== scroll) throw new Error('List navigation moved the document');
  await page.goto(`${url}/iframe.html?id=whip-textarea-suggestions--native-hold&viewMode=story&whip_a11y=manual`);
  await input.fill('/');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await input.press('Enter');
  await expect(page.getByLabel('Send count')).toHaveText('0');
  await input.press('Escape');
  await expect(page.getByLabel('Native holds released')).toHaveText('1');
  await page.waitForTimeout(500);
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await input.fill('/p');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await expect(page.getByRole('listbox')).toBeVisible();
  await input.press('Escape');
  await expect(page.getByLabel('Native holds released')).toHaveText('2');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Textarea suggestions: focus, keyboard, pointer, IME, empty Enter, long-list scroll, native hold races and narrow layout passed; axe passed excluding library focus-guard sentinels.');
} finally { await browser.close(); }
